import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createPublicClient,http} from 'viem';
import {sepolia} from 'viem/chains';
import {escrowAbi} from '../src/abi';
import {digest,evaluate,type Snapshot,type Terms} from '../src/policy';
import {createBundle} from '../src/bundle';
const config=JSON.parse(readFileSync('workflow/config.local.json','utf8')) as {apiUrl:string;terms:Terms};
assert.equal(config.apiUrl,'http://127.0.0.1:8755/delivery');
const response=await fetch(config.apiUrl,{signal:AbortSignal.timeout(5000)});assert.equal(response.status,200);
const delivery=await response.json() as {id:string;body:string};
const client=createPublicClient({chain:sepolia,transport:http('http://127.0.0.1:8754'),cacheTime:0});
assert.equal(await client.getChainId(),11155111);
const block=await client.getBlock({blockTag:'finalized'});
assert.ok((await client.getCode({address:config.terms.contract}))!.length>2);
const state=await client.readContract({address:config.terms.contract,abi:escrowAbi,functionName:'evidence',blockNumber:block.number});
assert.equal(state[0],digest(delivery.id));assert.equal(state[1],digest(delivery.body));
assert.equal(Number(state[4]),config.terms.deadline);assert.equal(Number(state[5]),config.terms.challengeSeconds);
assert.ok(state[6]>0n);
const now=Math.floor(Date.now()/1000);
const snapshot:Snapshot={id:delivery.id,chainId:11155111,contract:config.terms.contract,payee:state[2],amountWei:String(state[3]),artifactHash:state[1],disputed:state[7],released:state[8],blockNumber:String(block.number),blockHash:block.hash,observedAt:now,finalized:true,evidenceLevel:'local-evm'};
const receipt=evaluate(config.terms,{...delivery,accepted:true,acceptedAt:Number(state[6])},snapshot,now);
writeFileSync('evidence/local-providers-bundle.json',JSON.stringify(createBundle(config.terms,{...delivery,accepted:true,acceptedAt:Number(state[6])},snapshot,now),null,2));
const evidence={checkedAt:new Date().toISOString(),kind:'controlled-local-provider-check',rpc:'http://127.0.0.1:8754',api:config.apiUrl,checks:['Delivery HTTP 200','Private chain ID','Deployed contract code','Finalized header','Read at pinned block number','Artifact and milestone commitments','Deadline and challenge binding','Payer acceptance recorded'],receipt,creSimulation:false,publicProvider:false};
writeFileSync('evidence/local-providers.json',JSON.stringify(evidence,null,2));console.log(JSON.stringify(evidence,null,2));
