import ganache from 'ganache';
import solc from 'solc';
import {createServer} from 'node:http';
import {readFileSync,writeFileSync} from 'node:fs';
import {createPublicClient,createWalletClient,http,parseEther} from 'viem';
import {sepolia} from 'viem/chains';
import {privateKeyToAccount} from 'viem/accounts';
import {terms,body} from '../src/fixtures';
import {digest} from '../src/policy';
const chain=ganache.server({logging:{quiet:true},chain:{chainId:11155111,hardfork:'shanghai'},wallet:{deterministic:true}});
await chain.listen(8754,'127.0.0.1');
const pub=createPublicClient({chain:sepolia,transport:http('http://127.0.0.1:8754'),cacheTime:0});
const wallet=createWalletClient({chain:sepolia,transport:http('http://127.0.0.1:8754')});
const [payerAddress,payee]=await wallet.getAddresses();
const initial=chain.provider.getInitialAccounts();
const payer=privateKeyToAccount(initial[payerAddress.toLowerCase()].secretKey as `0x${string}`);
const out=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources:{'Escrow.sol':{content:readFileSync('contracts/EvidenceEscrow.sol','utf8')}},settings:{evmVersion:'shanghai',outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}})));
const c=out.contracts['Escrow.sol'].EvidenceEscrow;
const deadline=Number((await pub.getBlock()).timestamp)+86400;
const hash=await wallet.deployContract({account:payer,abi:c.abi,bytecode:`0x${c.evm.bytecode.object}`,args:[payee,digest(terms.id),digest(body),BigInt(deadline),60n],value:parseEther('0.015')});
const address=(await pub.waitForTransactionReceipt({hash})).contractAddress!;
const acceptance=await wallet.writeContract({account:payer,address,abi:c.abi,functionName:'accept'});await pub.waitForTransactionReceipt({hash:acceptance});
const config={schedule:'*/30 * * * * *',apiUrl:'http://127.0.0.1:8755/delivery',chainName:'ethereum-testnet-sepolia',evidenceLevel:'local-evm',terms:{...terms,payee,contract:address,deadline,challengeSeconds:60}};
writeFileSync('workflow/config.local.json',JSON.stringify(config,null,2));
const api=createServer((req,res)=>{if(req.url!=='/delivery'){res.writeHead(404);res.end();return;}res.setHeader('Content-Type','application/json');res.end(JSON.stringify({id:terms.id,body}));});
api.listen(8755,'127.0.0.1');
console.log('Private EVM: 127.0.0.1:8754; controlled delivery API: 127.0.0.1:8755/delivery');
console.log('Local config generated. Wait 60 seconds for the contractual challenge period before expecting REVIEW_READY.');
console.log('These services are LOCAL test providers, not public Sepolia or production delivery evidence.');
const timer=setInterval(async()=>{try{await chain.provider.request({method:'evm_mine',params:[]});}catch{}},5000);
const stop=async()=>{clearInterval(timer);api.close();await chain.close();process.exit(0);};process.on('SIGINT',stop);process.on('SIGTERM',stop);
