import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createPublicClient,http} from 'viem';
import {sepolia} from 'viem/chains';
import {escrowAbi} from '../src/abi';
import {createBundle,parseBundle} from '../src/bundle';
import type {Decision} from '../src/policy';
const [logPath='evidence/cre-simulation-success.txt',prefix='evidence/cre-ready',configPath='workflow/config.local.json']=process.argv.slice(2);
const text=readFileSync(logPath,'utf8').replace(/\u001b\[[0-9;]*[A-Za-z]/g,'');
const marker=text.indexOf('Workflow Simulation Result:');assert.ok(marker>=0,'CLI result marker missing');
const start=text.indexOf('{',marker);assert.ok(start>=0,'CLI result JSON missing');
let depth=0,inString=false,escape=false,end=-1;
for(let i=start;i<text.length;i++){const c=text[i];if(inString){if(escape){escape=false;}else if(c==='\\'){escape=true;}else if(c==='"'){inString=false;}}else if(c==='"'){inString=true;}else if(c==='{'){depth++;}else if(c==='}'){depth--;if(depth===0){end=i+1;break;}}}
assert.ok(end>start,'CLI result JSON incomplete');assert.match(text,/exit_code=0/,'CLI did not record success');
const result=JSON.parse(text.slice(start,end)) as Decision;
assert.equal(result.authorization,'HUMAN_REQUIRED');assert.equal(result.evidenceLevel,'local-evm');
const config=JSON.parse(readFileSync(configPath,'utf8'));
assert.ok(['http://127.0.0.1:8755/delivery','http://127.0.0.1:8756/delivery'].includes(config.apiUrl));
assert.deepEqual(result.terms,config.terms);
const response=await fetch(config.apiUrl,{signal:AbortSignal.timeout(5000)});assert.equal(response.status,200);
const delivery=await response.json() as {id:string;body:string};
const client=createPublicClient({chain:sepolia,transport:http('http://127.0.0.1:8754'),cacheTime:0});
const block=await client.getBlock({blockNumber:BigInt(result.snapshot.blockNumber)});assert.equal(block.hash,result.snapshot.blockHash);
const state=await client.readContract({address:result.terms.contract,abi:escrowAbi,functionName:'evidence',blockNumber:block.number});
const bundle=createBundle(result.terms,{...delivery,accepted:state[6]>0n,acceptedAt:Number(state[6])},result.snapshot,result.evaluatedAt);
assert.equal(bundle.receiptHash,result.receiptHash,'CLI receipt does not reproduce from delivery and pinned chain state');
parseBundle(JSON.stringify(bundle));
writeFileSync(prefix+'-result.json',JSON.stringify(result,null,2));
writeFileSync(prefix+'-bundle.json',JSON.stringify(bundle,null,2));
console.log(JSON.stringify({sourceLog:logPath,status:result.status,receiptHash:result.receiptHash,blockNumber:result.snapshot.blockNumber,pinnedBlockHashMatches:true,reproducedFingerprint:true,sourceAuthentication:'CLI execution log; portable JSON remains unsigned'},null,2));
